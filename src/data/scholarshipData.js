// CROSS-SCHEME DEDUPLICATION & CONFLICT DETECTION RULE ENGINE
// ─────────────────────────────────────────────────────────────────────────────

export const CONFLICT_RULES = {
  // Check if student is allowed to apply for a target scheme given active schemes
  evaluateApplicationConflict: (student, targetSchemeId) => {
    const activeApp = student.applications.find(a => a.status === 'disbursed' || a.status === 'in_progress' || a.status === 'action_required' || a.status === 'under_review')
    
    if (!activeApp) {
      return { hasConflict: false, reason: null, policyClause: null }
    }

    const currentScheme = SCHEMES.find(s => s.id === activeApp.schemeId)
    const targetScheme = SCHEMES.find(s => s.id === targetSchemeId)

    // Simultaneous Availing Rule
    if (activeApp.schemeId === targetSchemeId) {
      return {
        hasConflict: true,
        type: 'DUPLICATE_APPLICATION',
        title: 'Duplicate Application Detected',
        reason: `You already have an active application (${activeApp.id}) submitted for ${targetScheme.name} for the current academic session.`,
        policyClause: 'Section 4.2 of National Scholarship Guidelines: Only one active application per scheme per academic cycle is allowed.',
        existingApp: activeApp,
        canRelinquish: false
      }
    }

    // Special case: Basic Scheme and Top Class / High-Value Transition
    if (activeApp.schemeId === 'post-matric' && targetSchemeId === 'top-class') {
      return {
        hasConflict: true,
        type: 'SCHEME_SUPERSEDING',
        title: 'Cross-Portal Scheme Conflict: Post-Matric & Top Class',
        reason: `Our Unified Central Registry detected an active grant of '${currentScheme?.name || 'Current Grant'}' via NSP. Because Top Class covers 100% tuition plus living expenses, national regulations mandate that your existing grant must be transitioned or surrendered prior to final Top Class disbursement.`,
        policyClause: 'Operational Guidelines Para 7.1: A student admitted to a premier institution must relinquish basic post-matric assistance upon sanction of the Top Class Central Award.',
        existingApp: activeApp,
        canRelinquish: true,
        recommendation: 'Proceed with provisional Top Class submission. If shortlisted, ScholarBridge will automatically generate an automated No-Objection Certificate (NOC) and notify the State Directorate.'
      }
    }

    // General simultaneous conflict (e.g. CSSS vs PMRF / Doctoral Fellowship)
    if ((activeApp.schemeId === 'csss' || activeApp.schemeId === 'post-matric') && (targetSchemeId === 'nfst' || targetSchemeId === 'nos' || targetSchemeId === 'pmrf')) {
      return {
        hasConflict: true,
        type: 'SIMULTANEOUS_BENEFIT_BARRED',
        title: 'Strict GFR Rule 11: Concurrent Scholarship Barred',
        reason: `National registry check confirmed that Aadhaar ${student.aadhaarMasked} is currently receiving benefits under '${currentScheme?.name || 'Current Scheme'}'. Simultaneous receipt of doctoral fellowship (${targetScheme?.shortName || 'New Grant'}) is strictly prohibited under Government of India anti-double-dipping rules.`,
        policyClause: 'Rule 11 (General Financial Rules 2017): No scholar shall receive dual financial aid from Central/State Government for the same degree course.',
        existingApp: activeApp,
        canRelinquish: true,
        recommendation: 'To apply for the advanced fellowship, you must submit a formal relinquishment declaration for your existing grant.'
      }
    }

    return { hasConflict: false, reason: null, policyClause: null }
  }
}

